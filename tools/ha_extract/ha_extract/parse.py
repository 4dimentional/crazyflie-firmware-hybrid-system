"""Parse Crazyflie firmware C sources on the host with libclang.

The firmware is normally compiled for arm-none-eabi with a kconfig-generated
autoconf.h. For static analysis we parse with the host target instead and,
when no build output exists, substitute a stub autoconf.h.
"""
from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import clang.cindex as ci

REPO_ROOT = Path(__file__).resolve().parents[3]
TOOL_ROOT = Path(__file__).resolve().parents[1]
STUB_DIR = TOOL_ROOT / "_parse_stub"

# Mirrors INCLUDES in the top-level Makefile (vendor/ entries only resolve
# after `git submodule update --init`).
_SRC_INCLUDES = [
    "src/config",
    "src/platform/interface",
    "src/deck/interface",
    "src/deck/drivers/interface",
    "src/drivers/interface",
    "src/drivers/bosch/interface",
    "src/drivers/esp32/interface",
    "src/hal/interface",
    "src/modules/interface",
    "src/modules/interface/kalman_core",
    "src/modules/interface/lighthouse",
    "src/modules/interface/outlierfilter",
    "src/modules/interface/cpx",
    "src/modules/interface/p2pDTR",
    "src/modules/interface/controller",
    "src/modules/interface/estimator",
    "src/utils/interface",
    "src/utils/interface/kve",
    "src/utils/interface/lighthouse",
    "src/utils/interface/tdoa",
    "vendor/CMSIS/CMSIS/Core/Include",
    "vendor/CMSIS/CMSIS/DSP/Include",
    "vendor/FreeRTOS/include",
    "vendor/FreeRTOS/portable/GCC/ARM_CM4F",
]

# Minimal config so platform_defaults.h etc. take the cf2 code paths.
_STUB_AUTOCONF = """\
/* Stub autoconf.h for host-side parsing (generated by ha_extract). */
#pragma once
#define CONFIG_PLATFORM_CF2 1
#define CONFIG_CONTROLLER_PID 1
#define CONFIG_CONTROLLER_MELLINGER 1
#define CONFIG_ESTIMATOR_KALMAN 1
"""


@lru_cache(maxsize=1)
def clang_resource_include() -> Path | None:
    """Builtin headers (stddef.h, stdint.h, ...) missing from the pip wheel."""
    clang = shutil.which("clang")
    if clang is None:
        return None
    out = subprocess.run([clang, "-print-resource-dir"], capture_output=True, text=True)
    inc = Path(out.stdout.strip()) / "include"
    return inc if (inc / "stddef.h").exists() else None


def _generated_include_dir() -> Path:
    real = REPO_ROOT / "build" / "include" / "generated"
    if (real / "autoconf.h").exists():
        return real
    STUB_DIR.mkdir(exist_ok=True)
    (STUB_DIR / "autoconf.h").write_text(_STUB_AUTOCONF)
    return STUB_DIR


def compile_args() -> list[str]:
    args = ["-x", "c", "-std=gnu11", "-DCRAZYFLIE_FW", "-DARM_MATH_CM4", "-D__FPU_PRESENT=1"]
    builtin = clang_resource_include()
    if builtin is not None:
        args += ["-isystem", str(builtin)]
    for rel in _SRC_INCLUDES:
        p = REPO_ROOT / rel
        if p.is_dir():
            args.append(f"-I{p}")
    args.append(f"-I{_generated_include_dir()}")
    return args


@dataclass
class ParseResult:
    tu: ci.TranslationUnit
    errors: list[ci.Diagnostic]

    @property
    def ok(self) -> bool:
        return not self.errors


def parse_file(path: str | Path, extra_args: list[str] | None = None) -> ParseResult:
    path = Path(path)
    if not path.is_absolute():
        path = REPO_ROOT / path
    index = ci.Index.create()
    tu = index.parse(
        str(path),
        args=compile_args() + (extra_args or []),
        options=ci.TranslationUnit.PARSE_DETAILED_PROCESSING_RECORD,
    )
    errors = [d for d in tu.diagnostics if d.severity >= ci.Diagnostic.Error]
    return ParseResult(tu, errors)


def parse_source(code: str, filename: str = "snippet.c", extra_args: list[str] | None = None) -> ParseResult:
    """Parse a C snippet held in memory (no firmware include paths)."""
    args = ["-x", "c", "-std=gnu11"]
    builtin = clang_resource_include()
    if builtin is not None:
        args += ["-isystem", str(builtin)]
    index = ci.Index.create()
    tu = index.parse(filename, args=args + (extra_args or []), unsaved_files=[(filename, code)],
                     options=ci.TranslationUnit.PARSE_DETAILED_PROCESSING_RECORD)
    errors = [d for d in tu.diagnostics if d.severity >= ci.Diagnostic.Error]
    return ParseResult(tu, errors)


if __name__ == "__main__":
    import sys

    for f in sys.argv[1:]:
        r = parse_file(f)
        print(f"{f}: {'OK' if r.ok else f'{len(r.errors)} error(s)'}")
        for d in r.errors[:20]:
            print(f"  {d.location.file}:{d.location.line}: {d.spelling}")
